"""Render a Markdown model card from a training report."""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from churn_service.train import TrainingReport


def render_model_card(r: TrainingReport) -> str:
    """Return the model card as Markdown. Numbers come straight from the report."""
    cv_rows = "\n".join(
        f"| {name} | {s['roc_auc']:.3f} | {s['pr_auc']:.3f} |" for name, s in r.cv_scores.items()
    )
    imp_rows = "\n".join(f"| {f} | {v:.4f} |" for f, v in r.permutation_importance.items())
    m = r.test_metrics
    env = ", ".join(f"{k} {v}" for k, v in r.environment.items())
    return f"""# Model card: churn classifier

> Generated by `python -m churn_service.train --model-card MODEL_CARD.md`.
> **All data is synthetic.** These numbers describe performance on a simulated
> population, not on real customers.

## Model details
- **Model:** `{r.model_name}` (scikit-learn pipeline: preprocessing + classifier)
- **Version:** `{r.model_version}` — trained {r.trained_at}
- **Environment:** {env}
- **Output:** churn probability in [0, 1] plus a binary flag at threshold **{r.threshold:.4f}**

## Intended use
- Rank existing subscription customers by churn risk so a retention team can prioritise outreach.
- Decision support only. A human decides whether and how to contact a customer.

## Out of scope
- Any real customer base without retraining and re-validation on real data.
- Automated decisions with legal or similarly significant effect (GDPR Art. 22),
  pricing, or credit decisions.

## Training data
- {r.n_train:,} synthetic customers for training, {r.n_test:,} held out for testing
  (stratified split). Training churn rate: {r.churn_rate_train:.1%}.
- Churn is drawn from a known logistic model with noise (see `src/churn_service/data.py`).
- No personal data. `customer_id` is never used as a feature.

## Model selection (5-fold stratified CV on the training set)
| candidate | ROC-AUC | PR-AUC |
|---|---|---|
{cv_rows}

Selection metric: PR-AUC (churners are the minority class). The threshold was chosen
to maximise F1 on out-of-fold predictions, so the test set was never used for tuning.

## Test-set performance (held out, evaluated once)
| metric | value |
|---|---|
| ROC-AUC | {m['roc_auc']:.3f} |
| PR-AUC | {m['pr_auc']:.3f} |
| Brier score | {m['brier']:.3f} |
| Precision @ threshold | {m['precision']:.3f} |
| Recall @ threshold | {m['recall']:.3f} |
| F1 @ threshold | {m['f1']:.3f} |
| Share of customers flagged | {m['flagged_share']:.1%} |

## Feature importance (permutation, drop in PR-AUC on the test set)
| feature | importance |
|---|---|
{imp_rows}

## Caveats and risks
- `senior_citizen` is an age proxy. Using it to target or exclude customers needs a
  fairness review; check performance per group before any real use.
- The threshold maximises F1. A real deployment should set it from the cost of a
  retention offer vs. the value of a saved customer.
- Real churn drifts with prices and competitors. Monitor input distributions and
  realised churn, and retrain on a schedule.
"""
